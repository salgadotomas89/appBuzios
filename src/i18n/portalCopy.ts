export const portalCopy: Record<Language, PortalCopy> = { es, pt };

export function inputErrorText(language: Language, label: string, error: InputError): string {
  const text = portalCopy[language].input[error.code]
    .replace('{min}', String(error.min))
    .replace('{max}', String(error.max));
  // Los errores de conteo no nombran el campo, así que se antepone la etiqueta.
  return error.code.startsWith('count_') ? `${label}: ${text}` : text;
}
